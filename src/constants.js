// -----------------------------------------------------------------------------
// Constants: the local API of the Heatmiser neoHub, the feature roles, the
// manifest keys, the limits and the timings.
//
// The neoHub (written from the official "neoHub API" PDF of IMI Heatmiser,
// Rev 3.01, published on dev.heatmiser.com) answers a secure WebSocket on
// port 4243 of its local address. Each message carries the API token the
// user creates in the Heatmiser Neo app (Settings > API Access > Tokens):
//
//   {"message_type":"hm_get_command_queue",
//    "message":"{\"token\":\"…\",\"COMMANDS\":[{\"COMMAND\":\"{'GET_LIVE_DATA':0}\",\"COMMANDID\":1}]}"}
//
// answered by
//
//   {"command_id":1,"device_id":"D8:80:39:AD:0D:F0",
//    "message_type":"hm_set_command_response","response":"{…}"}
//
// The COMMAND itself is written the way the PDF shows it, with single
// quotes ({'FIRMWARE':0}); the MIT client heatmiser-neohub notes that the hub
// answers "Invalid Json" to the double-quoted form. The certificate of the hub
// is generated by the hub itself (the PDF says to skip its verification): it
// is pinned here instead (src/neohub/tls.js).
// -----------------------------------------------------------------------------

