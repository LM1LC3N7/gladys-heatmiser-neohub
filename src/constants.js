export const SECOND = 1_000;
export const MINUTE = 60 * SECOND;
export const HOUR = 60 * MINUTE;

export const TIMINGS = {
  /** The TLS connection (and the WebSocket upgrade) to the hub. */
  connectTimeout: 5 * SECOND,
  /** One command of the polling. */
  requestTimeout: 10 * SECOND,
  /** A connection closing is awaited this long before a new one opens. */
  closeWait: 500,
  /** Failed rounds: 1, 2, 5, 10, then 15 minutes, never shorter than the interval. */
  backoff: [MINUTE, 2 * MINUTE, 5 * MINUTE, 10 * MINUTE, 15 * MINUTE],
  /** A pause (backoff) is never longer than this, whatever /data holds. */
  pauseMax: HOUR,
  /** The publisher sends what is pending every second; unchanged states again every 30 min. */
  flushInterval: SECOND,
  stateHeartbeat: 30 * MINUTE,
  /** The "Test the connection" button reads at most this often. */
  testCooldown: 10 * SECOND,
  /** The button waits 30 s in Gladys: it answers by 25 s. */
  testBudget: 25 * SECOND,
  /**
   * Commands (Gladys waits 5 s for the ack; the ack comes by ~3.4 s): the
   * fresh read and the command must leave by 2.8 s after the click, or the
   * command is refused unsent (its turn in the queue or the lane is not
   * awaited longer); the answer is awaited until 3.4 s, after which the
   * command is "sent, without confirmation". A standby or an away answers by
   * 3.4 s too, and keeps on being sent after its ack when the hub is busy.
   */
  commandSendBy: 2_800,
  commandAnswerBy: 3_400,
  /** The fresh read of a command: 1.8 s at most, and 0.3 s left to send after it. */
  commandReadMax: 1_800,
  commandMinSend: 300,
  /** The first command waits this long for the others of a scene (then grouped). */
  gather: 50,
  /** Commands waiting their turn (a scene setting several zones), served one at a time. */
  commandQueue: 8,
  /** Reads after a command: its effect, then a check; never skipped (they wait their turn). */
  followUps: [5 * SECOND, 20 * SECOND, 95 * SECOND],
  /**
   * A standby or an away (the protective commands): a request of the polling
   * in flight for this long without an answer is cut for it (it does not
   * count as a failure); a failed attempt is tried again within this budget,
   * then kept in /data and sent again by the next reads (3 times at most).
   */
  stuckRead: SECOND,
  protectiveBudget: 250,
  protectiveResends: 3,
  /**
   * After a standby (or an away), a setpoint on the zone (on any zone for an
   * away) is refused for this long: only an explicit "Schedule" (or "Home")
   * lifts it sooner, right before it is written.
   */
  stopGuard: 10 * MINUTE,
  /**
   * The live data of the hub is refreshed about every 90 s (PDF p. 13): a stop
   * the hub answered is judged on a read sent at least this long after.
   */
  liveLag: 90 * SECOND,
  /** A read or a write of /data is never awaited longer; unreadable at start, read again every 10 s. */
  dataTimeout: 2 * SECOND,
  dataRetry: 10 * SECOND,
  /** The read again of an unreadable /data (in the background): a slow disk gets this long. */
  dataRetryTimeout: 30 * SECOND,
  /** The configuration of Gladys not read at start: new tries 5 s, 15 s, 1 min, then every 5 min. */
  configRetry: [5 * SECOND, 15 * SECOND, MINUTE, 5 * MINUTE],
};
